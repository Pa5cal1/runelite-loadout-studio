 @Test public void declaredTrouverIdsRemainSelectableAndExactThroughBothExports(){
  assertEquals(145,IDS.length);SetupCodec codec=new SetupCodec(RuneLiteAPI.GSON);
  for(int id:IDS){assertEquals(id,ItemCatalogue.selectionId(id));assertFalse(AutomaticItemExclusions.avoidDefault(id));JsonObject p=SetupCodec.blank("Locked item");SetupCodec.setup(p).getAsJsonArray("inv").set(0,SetupCodec.item(id,1));SetupCodec.rebuildLayout(p);assertEquals(id,SetupCodec.id(SetupCodec.setup(codec.importText(codec.inventory(p)).get(0)).getAsJsonArray("inv").get(0)));for(boolean legacy:new boolean[]{false,true})assertEquals(id,SetupCodec.id(SetupCodec.setup(codec.importText(codec.bank(p,legacy)).get(0)).getAsJsonArray("inv").get(0)));}
 }
 @Test public void lockedCapesResolveAndFilterTheirExactBankItems(){
  int[] capes={ItemID.SKILLCAPE_MAX_INFERNALCAPE_TROUVER,ItemID.SKILLCAPE_MAX_FIRECAPE_TROUVER,ItemID.TZHAAR_CAPE_FIRE_TROUVER,ItemID.INFERNAL_CAPE_TROUVER};String[] names={"Infernal max cape (l)","Fire max cape (l)","Fire cape (l)","Infernal cape (l)"};ItemCatalogue catalogue=new ItemCatalogue();
  for(int i=0;i<capes.length;i++){int id=capes[i];catalogue.add(id,names[i],false,-1,-1,1,false,true);assertEquals(id,catalogue.firstExact(names[i]).id);JsonObject p=SetupCodec.blank(names[i]);SetupCodec.setup(p).getAsJsonArray("eq").set(1,SetupCodec.item(id,1));SetupCodec.rebuildLayout(p);BankFilterTest.FakeBank bank=new BankFilterTest.FakeBank();bank.open=true;new StudioBankFilter(bank,"studio").select(p);assertTrue(bank.matches.test(id));for(int other:capes)if(other!=id)assertFalse(bank.matches.test(other));assertTrue(java.util.Arrays.stream(bank.layout).anyMatch(value->value==id));}
 }
